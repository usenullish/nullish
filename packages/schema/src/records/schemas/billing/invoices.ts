import { createInsertSchema, createSelectSchema, createUpdateSchema } from "drizzle-orm/zod";
import { InvoicesSchema, LinesSchema } from "../../../db/schemas/billing/invoices";
import {
  INSERT_OMIT_FIELDS,
  ORGANIZATION_ID_OMIT_FIELD,
  UPDATE_OMIT_FIELDS,
  UPDATE_REQUIRED_FIELDS,
} from "../../../primitives";
import { InvoiceLineType, InvoiceStatus } from "../../../db";
import * as z from "zod";
import { refineCurrencyValue, refineExchangeRate } from "../../../db/_refine";

// Drizzle does not correctly infer the enum
const refineInvoiceStatusEnums = {
  status: z.enum(InvoiceStatus),
};

const refineInvoices = {
  ...refineInvoiceStatusEnums,
  exchangeRate: refineExchangeRate,
};

const refineOptionalInvoices = {
  ...refineInvoiceStatusEnums,
  exchangeRate: refineExchangeRate.optional(),
};

const refineInvoiceLineTypeEnums = {
  type: z.enum(InvoiceLineType),
};

const refineLineAmounts = {
  unitPrice: refineCurrencyValue,
};

// Number and paymentReference are generated by triggers
const autoGeneratedOmitFields = {
  number: true,
  paymentReference: true,
} as const;

export const SelectInvoicesSchema = createSelectSchema(InvoicesSchema, refineInvoices);
export const InsertInvoicesSchema = createInsertSchema(InvoicesSchema, refineOptionalInvoices).omit(
  // Invoice can only be created as draft
  {
    ...ORGANIZATION_ID_OMIT_FIELD,
    ...INSERT_OMIT_FIELDS,
    ...autoGeneratedOmitFields,
    status: true,
  },
);
export const UpdateInvoicesSchema = createUpdateSchema(InvoicesSchema, refineOptionalInvoices)
  .omit({
    ...ORGANIZATION_ID_OMIT_FIELD,
    ...UPDATE_OMIT_FIELDS,
    organizationId: true,
    clientId: true,
    ...autoGeneratedOmitFields,
  })
  .required(UPDATE_REQUIRED_FIELDS);

export const SelectLinesSchema = createSelectSchema(LinesSchema, {
  ...refineInvoiceLineTypeEnums,
  ...refineLineAmounts,
}).omit({
  ...ORGANIZATION_ID_OMIT_FIELD,
  invoiceId: true,
});
export const InsertLinesSchema = createInsertSchema(LinesSchema, {
  ...refineInvoiceLineTypeEnums,
  ...refineLineAmounts,
}).omit({
  ...INSERT_OMIT_FIELDS,
  ...ORGANIZATION_ID_OMIT_FIELD,
  invoiceId: true,
});
export const UpdateLinesSchema = createUpdateSchema(LinesSchema, {
  ...refineInvoiceLineTypeEnums,
  unitPrice: refineLineAmounts.unitPrice.optional(),
}).omit({
  ...UPDATE_OMIT_FIELDS,
  ...ORGANIZATION_ID_OMIT_FIELD,
  invoiceId: true,
});

export const FilterInvoicesSchema = z.strictObject({
  status: refineInvoiceStatusEnums.status.optional(),
  clientId: SelectInvoicesSchema.shape.clientId.optional(),
  issueOnFrom: SelectInvoicesSchema.shape.issueOn.optional(),
  issueOnTo: SelectInvoicesSchema.shape.issueOn.optional(),
});

export const FilterLinesSchema = z.strictObject({
  type: refineInvoiceLineTypeEnums.type.optional(),
});
